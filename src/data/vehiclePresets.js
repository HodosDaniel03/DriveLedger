export function getPresetById(id) {
  return VEHICLE_PRESETS.find((p) => p.id === id) || VEHICLE_PRESETS[0];
}

export function filterVehiclePresets({
  bodyType = 'all',
  brand = 'All Brands',
  fuelType = 'all',
  searchQuery = '',
  maxPrice = Infinity,
}) {
  const q = searchQuery.trim().toLowerCase();
  return VEHICLE_PRESETS.filter((preset) => {
    if (bodyType !== 'all' && preset.bodyType !== bodyType) return false;
    if (brand !== 'All Brands' && preset.brand !== brand) return false;
    if (fuelType !== 'all' && preset.fuelType.toLowerCase() !== fuelType.toLowerCase()) return false;
    if (preset.purchasePriceUsd > maxPrice) return false;
    if (q) {
      const inName = preset.name.toLowerCase().includes(q);
      const inBrand = preset.brand.toLowerCase().includes(q);
      const inModel = preset.modelName.toLowerCase().includes(q);
      const inEngine = (preset.engineCode || '').toLowerCase().includes(q);
      const inDefect = (preset.knownRiskNotes || '').toLowerCase().includes(q);
      const inTag = (preset.criticalDefectTag || '').toLowerCase().includes(q);
      return inName || inBrand || inModel || inEngine || inDefect || inTag;
    }
    return true;
  });
}
